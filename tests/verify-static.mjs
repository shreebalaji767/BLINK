import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const html = readFileSync("index.html", "utf8");
const app = readFileSync("app-social-requests.js", "utf8");
const css = readFileSync("styles.css", "utf8");
const activeScripts = [...html.matchAll(/<script[^>]+src="([^"]+)"/g)].map((m) => m[1]).filter((src) => src.includes("app-social-requests.js"));
assert.equal(activeScripts.length, 1, "active app must load exactly once");
assert.match(activeScripts[0], /\?v=[a-f0-9]{8,}/, "active app URL must be cache-busted");
const htmlIds = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
const appIds = new Set([...app.matchAll(/\$\("#([^"]+)"\)/g)].map((m) => m[1]));
assert.deepEqual([...appIds].filter((id) => !htmlIds.has(id)), [], "all app DOM selectors must exist");
for (const action of ["like", "react", "save", "follow", "comment", "reply"]) assert.ok(app.includes('case"' + action + '"'), "missing post action: " + action);
for (const action of ["profile", "add", "accept", "decline", "cancel"]) assert.ok(app.includes('action==="' + action + '"'), "missing social action: " + action);
for (const view of ["feed", "following", "trending", "saved", "directory", "profile", "friends"]) assert.ok(html.includes('data-view="' + view + '"'), "missing navigation view: " + view);
assert.ok(app.includes("ensureIncomingRequests(3,5)"), "incoming NPC requests should be seeded");
assert.ok(app.includes("const readLocalArray=") && app.includes("const writeLocalArray="), "safe local storage helpers must exist");
assert.ok(!/JSON\.parse\(localStorage\.getItem/.test(app), "unguarded localStorage JSON parsing found");
assert.ok(css.length > 1000, "responsive stylesheet missing");
assert.match(html, /name="viewport"/, "mobile viewport metadata missing");
console.log("BLINK static smoke checks passed.");
